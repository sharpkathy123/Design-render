"""A design's shareable folder (Design-render, 2026-11-11: "a folder for all
the deliverables for each thing we design ... to share with other people").

    python3 tools/build_deliverables.py bed-frame     # one design
    python3 tools/build_deliverables.py               # every design with a share.yaml

From designs/<name>/share.yaml (the title, a summary, which renders with
their captions, which drawings, the guide), writes deliverables/<name>/:

    README.md                 the page GitHub shows: pictures, links, the design
    <name>-build-packet.pdf   everything in one printable file
    <drawing>.svg and .pdf    each drawing, sharp at any zoom, and printable
    files:                    anything else listed (3D models and their notes)
    BUILD.md                  the build guide, if the design has one
    renders/                  the pictures

and deliverables/README.md, the list of every design. Everything there is
generated: change the design's own files and run this again, never edit
deliverables/ by hand. PDFs need Node's playwright (preinstalled here).
"""
import datetime
import html
import os
import re
import shutil
import subprocess
import sys
import tempfile

import markdown
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGNS = os.path.join(ROOT, "designs")
OUT = os.path.join(ROOT, "deliverables")
REPO = "https://github.com/sharpkathy123/Design-render"
GENERATED = "<!-- Generated by tools/build_deliverables.py from designs/%s/: edit those, not this. -->\n"


def section(md, heading):
    """The text under '## heading' in a Markdown file, up to the next '## '."""
    m = re.search(r"^## %s\s*\n(.*?)(?=^## |\Z)" % re.escape(heading), md, re.S | re.M)
    return m.group(1).strip() if m else ""


def relink(md, name, copied):
    """Links to files that aren't copied point back to the design's folder."""
    def fix(m):
        target = m.group(2)
        if re.match(r"[a-z]+:|#|/", target) or target.split("#")[0] in copied:
            return m.group(0)
        return "%s(../../designs/%s/%s)" % (m.group(1), name, target)
    return re.sub(r"(\[[^\]]*\])\(([^)\s]+)\)", fix, md)


def md_html(md):
    # (Python-Markdown nests a list only at a 4-space indent; GitHub also takes 3, as BUILD.md uses)
    md = re.sub(r"^ {3}(?=[-*] |\S)", "    ", md, flags=re.M)
    md = re.sub(r"^ {5}(?=\S)", "      ", md, flags=re.M)
    return markdown.markdown(md, extensions=["tables", "sane_lists"])


def node_pdf(src, out, mode, title=""):
    r = subprocess.run(["node", os.path.join(ROOT, "tools", "pdf_print.js"), src, out, mode, title],
                       capture_output=True, text=True, cwd=ROOT)
    if r.returncode:
        sys.exit("PDF failed for %s:\n%s" % (out, r.stderr[-2000:]))


CSS = """
body{font-family:Georgia,'Times New Roman',serif;color:#2a2724;font-size:11pt;line-height:1.45;margin:0}
h1{font-size:26pt;font-weight:normal;margin:0 0 6pt} h2{font-size:15pt;margin:18pt 0 6pt;border-bottom:1px solid #ccc}
h3{font-size:12pt;margin:12pt 0 4pt}
table{border-collapse:collapse;width:100%;font-size:9.5pt;margin:6pt 0;break-inside:avoid} th,td{border:1px solid #ccc;padding:3pt 5pt;text-align:left;vertical-align:top}
th{background:#f2efe8} a{color:#6b3e14}
.lede{font-size:12.5pt;color:#444} .cover img{width:100%;border-radius:3px;margin:14pt 0}
.figs{display:grid;grid-template-columns:1fr 1fr;gap:10pt} .figs figure{margin:0;break-inside:avoid}
.figs img{width:100%;border-radius:2px} figcaption{font-size:9pt;color:#555;margin-top:2pt}
.newpage{break-before:page} .drawing{page:drawing;break-before:page;text-align:center}
.drawing img{max-width:100%;max-height:6.3in} .drawing h2{text-align:left}
@page drawing{size:11in 8.5in;margin:0.4in}
.meta{color:#777;font-size:9pt}
"""


def build(name):
    d = os.path.join(DESIGNS, name)
    cfg = yaml.safe_load(open(os.path.join(d, "share.yaml")))
    out = os.path.join(OUT, name)
    if os.path.isdir(out):
        shutil.rmtree(out)
    os.makedirs(os.path.join(out, "renders"))
    today = datetime.date.today()
    date = "%s %d, %d" % (today.strftime("%B"), today.day, today.year)
    title = cfg["title"]
    copied = set()

    # the renders
    for r in cfg.get("renders", []):
        shutil.copy2(os.path.join(d, r["file"]), os.path.join(out, r["file"]))
        copied.add(r["file"])
    # the drawings, each as SVG and a landscape PDF
    drawings = []
    for dr in cfg.get("drawings", []):
        svg = dr["file"]
        shutil.copy2(os.path.join(d, svg), os.path.join(out, svg))
        pdf = svg[:-4] + ".pdf"
        with tempfile.NamedTemporaryFile("w", suffix=".html", dir=out, delete=False) as f:
            f.write('<!doctype html><meta charset="utf-8"><style>@page{size:11in 8.5in;margin:0.4in}'
                    'body{margin:0}img{width:100%%;height:7.6in;object-fit:contain}</style><img src="%s">' % svg)
        node_pdf(f.name, os.path.join(out, pdf), "landscape")
        os.remove(f.name)
        copied |= {svg, pdf}
        drawings.append((dr["title"], svg, pdf))
    # other files to share as they are (3D models, with their notes)
    extras = []
    for fl in cfg.get("files", []):
        dst = os.path.join(out, fl["file"])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(os.path.join(d, fl["file"]), dst)
        copied.add(fl["file"])
        extras.append(fl)
    # the guide
    guide_md = ""
    if cfg.get("guide"):
        copied.add(cfg["guide"])
        guide_md = open(os.path.join(d, cfg["guide"])).read()
    design_md = open(os.path.join(d, "README.md")).read()
    the_design = section(design_md, "The design")
    packet = "%s-build-packet.pdf" % name
    copied.add(packet)
    if guide_md:
        open(os.path.join(out, cfg["guide"]), "w").write(GENERATED % name + relink(guide_md, name, copied))

    # the packet: cover, the design, pictures, drawings, the guide
    figs = "".join('<figure><img src="%s"><figcaption>%s</figcaption></figure>' % (r["file"], html.escape(r["caption"]))
                   for r in cfg.get("renders", [])[1:])
    page = ['<!doctype html><html><head><meta charset="utf-8"><title>%s</title><style>%s</style></head><body>' % (html.escape(title), CSS),
            '<div class="cover"><h1>%s</h1><p class="lede">%s</p><img src="%s"><p class="meta">Updated %s. '
            'Online: %s/tree/main/deliverables/%s</p></div>' % (html.escape(title), html.escape(cfg["summary"]),
                                                                cfg.get("cover", cfg["renders"][0]["file"]), date, REPO, name),
            '<div class="newpage"><h2>The design</h2>%s</div>' % md_html(the_design),
            '<div class="figs">%s</div>' % figs]
    for t, svg, _ in drawings:
        page.append('<div class="drawing"><h2>%s</h2><img src="%s"></div>' % (html.escape(t), svg))
    if guide_md:
        g = re.sub(r"^# .*\n", "", guide_md, count=1)
        page.append('<div class="newpage"><h2>How to build it</h2>%s</div>' % md_html(relink(g, name, copied)).replace("<h2>", "<h3>").replace("</h2>", "</h3>"))
    page.append("</body></html>")
    tmp = os.path.join(out, "_packet.html")
    open(tmp, "w").write("".join(page))
    node_pdf(tmp, os.path.join(out, packet), "packet", "%s, %s" % (title, date))
    os.remove(tmp)

    # the page GitHub shows
    lines = [GENERATED % name, "# %s\n" % title, cfg["summary"] + "\n",
             "![%s](%s)\n" % (cfg["renders"][0]["caption"], cfg.get("cover", cfg["renders"][0]["file"])),
             "**[Download the build packet (PDF)](%s)**: the pictures, the drawings and the build guide in one printable file.\n" % packet,
             "## Drawings\n"]
    for t, svg, pdf in drawings:
        lines.append("- **%s:** [view](%s) (sharp at any zoom), [PDF to print](%s)" % (t, svg, pdf))
    if guide_md:
        lines.append("\n## How to build it\n\n[The build guide](%s): materials with estimated prices, tools, and the steps in order.\n" % cfg["guide"])
    if extras:
        lines.append("## 3D model\n")
        for fl in extras:
            lines.append("- **%s:** [%s](%s)" % (fl["title"], os.path.basename(fl["file"]), fl["file"]))
        lines.append("")
    lines.append("## Pictures\n")
    for r in cfg.get("renders", []):
        lines.append("![%s](%s)\n*%s*\n" % (r["caption"], r["file"], r["caption"]))
    lines.append("## The design\n\n" + relink(the_design, name, copied) + "\n")
    lines.append("---\nUpdated %s. Made with [Design-render](../../README.md); the model and its sources are in "
                 "[designs/%s](../../designs/%s/).\n" % (date, name, name))
    open(os.path.join(out, "README.md"), "w").write("\n".join(lines))
    print("DELIVERABLES %s -> %s" % (name, os.path.relpath(out, ROOT)))
    return cfg


def index():
    rows = []
    for name in sorted(os.listdir(OUT)):
        p = os.path.join(DESIGNS, name, "share.yaml")
        if not os.path.exists(p):
            continue
        cfg = yaml.safe_load(open(p))
        cover = cfg.get("cover", cfg["renders"][0]["file"])
        rows.append('### [%s](%s/)\n\n<a href="%s/"><img src="%s/%s" width="420" alt="%s"></a>\n\n%s\n\n'
                    '[Build packet (PDF)](%s/%s-build-packet.pdf)\n'
                    % (cfg["title"], name, name, name, cover, html.escape(cfg["title"]), cfg["summary"], name, name))
    open(os.path.join(OUT, "README.md"), "w").write(
        "<!-- Generated by tools/build_deliverables.py. -->\n# Designs\n\nEverything for each design, ready to share: "
        "pictures, drawings, a build guide, and one printable PDF. Open a design for its page.\n\n" + "\n".join(rows))


def main():
    names = sys.argv[1:] or [n for n in sorted(os.listdir(DESIGNS)) if os.path.exists(os.path.join(DESIGNS, n, "share.yaml"))]
    for n in names:
        build(n)
    index()


if __name__ == "__main__":
    main()
